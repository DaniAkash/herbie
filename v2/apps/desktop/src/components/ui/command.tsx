import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { cn } from "cn"

import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"
import {
  InputGroup,
  InputGroupAddon,
} from "@/components/ui/input-group"
import { SearchIcon, CheckIcon } from "lucide-react"

import { useTouchCapable } from "@/lib/hooks/use-touch-capable"

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex size-full flex-col overflow-hidden rounded-xl! bg-popover p-1 text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = false,
  ...props
}: Omit<React.ComponentProps<typeof Dialog>, "children"> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
  children: React.ReactNode
}) {
  return (
    <Dialog {...props}>
      <DialogContent
        className={cn(
          "top-1/3 translate-y-0 overflow-hidden rounded-xl! p-0",
          className
        )}
        showCloseButton={showCloseButton}
      >
        {/* Inside the popup, or the dialog has no accessible name. */}
        <DialogHeader className="sr-only">
          <DialogTitle>{title}</DialogTitle>
          <DialogDescription>{description}</DialogDescription>
        </DialogHeader>
        {/* cmdk keeps its state on a store the parts read through context, so
         * every part has to sit inside a Command. The dialog already draws the
         * surface, so this one only carries the state. */}
        <Command className="bg-transparent p-0">{children}</Command>
      </DialogContent>
    </Dialog>
  )
}

function CommandInput({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Input>) {
  /* iOS zooms the page on a focused field below 16px and does not zoom back
   * out when the field goes away, so the whole app is left scaled. */
  const canTouch = useTouchCapable()
  return (
    <div
      data-slot="command-input-wrapper"
      className="border-b border-border p-2"
    >
      <InputGroup className="h-9! rounded-lg! border-border bg-input shadow-none! *:data-[slot=input-group-addon]:pl-2! dark:bg-input">
        <CommandPrimitive.Input
          data-slot="command-input"
          className={cn(
            "w-full text-sm outline-hidden disabled:cursor-not-allowed disabled:opacity-50",
            canTouch && "text-base",
            className
          )}
          {...props}
        />
        <InputGroupAddon>
          <SearchIcon className="size-4 shrink-0 opacity-50" />
        </InputGroupAddon>
        <InputGroupAddon align="inline-end">
          <kbd className="rounded-chip border border-border bg-popover px-1.5 py-0.5 text-[10px] text-ink-2 leading-none">
            ESC
          </kbd>
        </InputGroupAddon>
      </InputGroup>
    </div>
  )
}

